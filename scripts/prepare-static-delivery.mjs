import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Only Vite output receives these rules. API, HTML, uploads and sessions are outside this directory.
const target = fileURLToPath(new URL('../public/build/.htaccess', import.meta.url));
await writeFile(target, `# Generated by npm run build. Apache shared hosting; optional modules only.
<IfModule mod_deflate.c>
  <IfModule mod_filter.c>
    AddOutputFilterByType DEFLATE application/javascript text/javascript text/css application/json image/svg+xml
  </IfModule>
</IfModule>

<IfModule mod_headers.c>
  # Vite content hashes change whenever content changes. Never apply to manifest.json.
  <FilesMatch "-[A-Za-z0-9_-]{8,}\\.(js|css)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <Files "manifest.json">
    Header set Cache-Control "no-cache"
  </Files>
</IfModule>
`);
console.log('Static delivery rules generated in public/build/.htaccess');
