test('Web: total manual permite manutenção sem itens e sem data da próxima revisão',async({page})=>{
  await page.setViewportSize({width:1440,height:900});
  await login(page);
  const stamp=Date.now().toString();
  const bank=await api(page,'/expense-control/catalogs/institutions','POST',{name:'Manual '+stamp,due_day:10,active:true,color:'#c09030'});
  const kind=await api(page,'/expense-control/catalogs/types','POST',{name:'Carros '+stamp,active:true});
  await page.getByRole('button',{name:'Controle de Gasto',exact:true}).click();
  await page.getByRole('tab',{name:'Carros'}).click();
  await page.getByRole('button',{name:'Cadastrar veículo'}).click();
  await page.getByPlaceholder('Ex.: Peugeot 3008').fill('Veículo manual '+stamp);
  await page.getByRole('button',{name:'Salvar veículo'}).click();
  await expect(page.getByText('Veículo cadastrado com sucesso.')).toBeVisible();
  await page.locator('.cgv-intro-cards').getByRole('button',{name:/Manutenção/}).click();
  const form=page.getByTestId('vehicle-event-form');
  await form.getByLabel('Oficina / local da manutenção').fill('Oficina Manual');
  await expect(form.getByLabel('Próxima revisão — data')).toBeEmpty();
  await form.getByRole('checkbox',{name:'Informar valor total manualmente'}).check();
  await form.getByLabel('Valor total manual (R$)').fill('1.500,00');
  await form.getByLabel('Responsável *').selectOption('one');
  await form.getByLabel('Instituição para cobrança *').selectOption(String(bank.body.id));
  await form.getByLabel('Tipo de dívida *').selectOption(String(kind.body.id));
  await form.getByRole('button',{name:'Registrar despesa e histórico'}).click();
  await expect(page.getByText(/Registrado no histórico do carro/)).toBeVisible();
  const cars=await api(page,'/expense-control/vehicles');
  expect(cars.status).toBe(200);
  const event=cars.body.events.find((x:{vehicle_name:string})=>x.vehicle_name==='Veículo manual '+stamp);
  expect(event).toBeDefined();
  expect(event.next_due_on).toBeNull();
  expect(event.work_notes).toBeNull();
  expect(event.items).toEqual([]);
  const debt=await api(page,'/expense-control/debts/'+event.debt_id);
  expect(debt.body.debt.amount_cents).toBe(150000);
  expect(debt.body.debt.responsibility).toBe('one');
});

